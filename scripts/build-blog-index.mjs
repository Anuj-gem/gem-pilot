/**
 * Build-time codegen: read content/blog/*.md and emit
 * src/lib/blog-data.generated.ts with all posts inlined as a static
 * TypeScript constant.
 *
 * Why: Next.js 16's build tracer + Vercel deploys did NOT reliably
 * include content/ in the runtime bundle, so fs.readFile at request
 * time returned empty → blog index showed "No posts yet" and
 * /blog/[slug] 404'd. Inlining at build time removes the filesystem
 * dependency entirely. Anuj 2026-04-28.
 *
 * Wired into the `prebuild` npm script so it runs automatically before
 * `next build` (and before `next dev` if invoked manually).
 *
 * Usage:
 *   node scripts/build-blog-index.mjs
 */

import fs from 'node:fs/promises'
import fsSync from 'node:fs'
import path from 'node:path'
import matter from 'gray-matter'

const ROOT = process.cwd()
const POSTS_DIR = path.join(ROOT, 'content', 'blog')
const OUT_FILE = path.join(ROOT, 'src', 'lib', 'blog-data.generated.ts')

const files = fsSync.existsSync(POSTS_DIR)
  ? (await fs.readdir(POSTS_DIR)).filter(
      (f) => (f.endsWith('.md') || f.endsWith('.mdx')) && f !== 'README.md'
    )
  : []

const posts = []
for (const file of files) {
  const raw = await fs.readFile(path.join(POSTS_DIR, file), 'utf-8')
  const parsed = matter(raw)
  const data = parsed.data || {}
  const title = typeof data.title === 'string' ? data.title : ''
  const slug = typeof data.slug === 'string' && data.slug.trim()
    ? data.slug.trim()
    : file.replace(/\.(md|mdx)$/, '')
  const date = typeof data.date === 'string'
    ? data.date
    : data.date instanceof Date
      ? data.date.toISOString().slice(0, 10)
      : ''
  const summary = typeof data.summary === 'string' ? data.summary : ''
  const author = typeof data.author === 'string' ? data.author : 'Anuj Kommareddy'
  const og_image = typeof data.og_image === 'string' ? data.og_image : null
  const draft = data.draft === true
  if (!title || !slug || !date) {
    console.log(`  · skip ${file} — missing required frontmatter (title/slug/date)`)
    continue
  }
  posts.push({ slug, title, date, summary, author, og_image, draft, content: parsed.content })
}

posts.sort((a, b) => (a.date < b.date ? 1 : -1))

const banner = `// AUTO-GENERATED by scripts/build-blog-index.mjs — do NOT edit by hand.
// Source: content/blog/*.md
// Regenerated by the prebuild script before every \`next build\`.
//
// To add a post: drop a .md file in content/blog/ with the right
// frontmatter, then run \`npm run build\` (or \`node scripts/build-blog-index.mjs\`
// if you just want to refresh the index for dev).

`

const body = `import type { BlogPost } from './blog'

export const BLOG_POSTS: BlogPost[] = ${JSON.stringify(posts, null, 2)}
`

await fs.writeFile(OUT_FILE, banner + body, 'utf-8')

console.log(`✓ Wrote ${posts.length} post${posts.length === 1 ? '' : 's'} → ${path.relative(ROOT, OUT_FILE)}`)
for (const p of posts) {
  console.log(`  · ${p.slug} — ${p.title}${p.draft ? ' (draft)' : ''}`)
}
